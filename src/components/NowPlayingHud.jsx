// src/components/NowPlayingHud.jsx
// Floating Now Playing HUD with mini-oscilloscope, active root key, and 1-click .wav export
import { useEffect, useRef, useState } from 'react'
import { TRACK_ACOUSTIC_PROFILES } from '../audio/mapping.js'
import { renderSoundscapeWav } from '../audio/engine.js'
import { readColumn } from '../audio/analyse.js'

export default function NowPlayingHud({
  track,
  playing,
  synthRef,
  mediaRef,
  config,
  onOpenDiscover,
}) {
  const canvasRef = useRef(null)
  const [downloading, setDownloading] = useState(false)

  const profile = TRACK_ACOUSTIC_PROFILES[track?.id] || {
    rootNote: 'C3',
    scale: 'pentatonic',
    timbreName: 'Orbital Harmonics',
  }

  // Mini oscilloscope animation (battery-optimized: halts RAF when paused or hidden)
  useEffect(() => {
    let animId
    const canvas = canvasRef.current
    if (!canvas) return
    const ctx = canvas.getContext('2d')

    function drawResting() {
      ctx.fillStyle = 'rgba(15, 10, 51, 1)'
      ctx.fillRect(0, 0, canvas.width, canvas.height)
      ctx.strokeStyle = '#c3b8ea'
      ctx.lineWidth = 1.5
      ctx.beginPath()
      ctx.moveTo(0, canvas.height / 2)
      ctx.lineTo(canvas.width, canvas.height / 2)
      ctx.stroke()
    }

    if (!playing || !synthRef?.current) {
      drawResting()
      return
    }

    function draw() {
      if (document.hidden) {
        animId = requestAnimationFrame(draw)
        return
      }
      animId = requestAnimationFrame(draw)
      ctx.fillStyle = 'rgba(15, 10, 51, 0.4)'
      ctx.fillRect(0, 0, canvas.width, canvas.height)

      const wave = synthRef.current.getWaveform()
      if (!wave) return

      ctx.lineWidth = 2
      ctx.strokeStyle = '#7ff0ff'
      ctx.beginPath()

      const sliceWidth = canvas.width / wave.length
      let x = 0

      for (let i = 0; i < wave.length; i++) {
        const v = wave[i] / 128.0
        const y = (v * canvas.height) / 2

        if (i === 0) ctx.moveTo(x, y)
        else ctx.lineTo(x, y)

        x += sliceWidth
      }
      ctx.stroke()
    }

    draw()
    return () => {
      if (animId) cancelAnimationFrame(animId)
    }
  }, [playing, synthRef])

  const handleDownloadWav = async () => {
    if (!mediaRef?.current) return
    setDownloading(true)
    try {
      const trackConfig = {
        ...config,
        ...(TRACK_ACOUSTIC_PROFILES[track?.id] || {}),
      }
      const metadata = {
        title: track?.title || 'Earth Jukebox Sonification',
        credit: track?.credit || "NASA's Scientific Visualization Studio",
        comment: 'audio generated by Earth Jukebox code (AI-assisted code, reviewed by the team)',
        date: new Date().toISOString().slice(0, 10),
      }
      const wavBlob = await renderSoundscapeWav(readColumn, mediaRef.current, trackConfig, 14, metadata)
      const url = URL.createObjectURL(wavBlob)
      const a = document.createElement('a')
      a.href = url
      a.download = `${track?.id || 'earth'}-soundscape.wav`
      document.body.appendChild(a)
      a.click()
      document.body.removeChild(a)
      URL.revokeObjectURL(url)
    } catch (err) {
      console.error('WAV export error:', err)
      alert('Could not generate WAV file: ' + err.message)
    } finally {
      setDownloading(false)
    }
  }

  return (
    <div className="now-playing-hud" aria-label="Now playing monitor">
      <div className="now-playing-left">
        <canvas
          ref={canvasRef}
          width={72}
          height={32}
          className="oscilloscope-canvas"
          aria-hidden="true"
        />
        <div className="now-playing-meta">
          <div className="meta-top">
            <span className="live-indicator">{playing ? 'LIVE AUDIO' : 'PAUSED'}</span>
            <span className="key-tonic-tag">Key: {profile.rootNote}</span>
            <span className="scale-tag">{profile.scale}</span>
          </div>
          <span className="timbre-label">{profile.timbreName}</span>
        </div>
      </div>

      <div className="now-playing-actions">
        <button
          type="button"
          className="discover-btn"
          onClick={onOpenDiscover}
          title="Open Spectral Distribution & Acoustic DNA"
        >
          Discover NASA
        </button>

        <button
          type="button"
          className="download-wav-btn"
          onClick={handleDownloadWav}
          disabled={downloading}
          title="Download 14-second CD-quality .wav soundscape"
        >
          {downloading ? 'Rendering...' : 'Save .wav'}
        </button>
      </div>
    </div>
  )
}
