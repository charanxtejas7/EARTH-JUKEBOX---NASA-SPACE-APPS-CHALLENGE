// src/components/SoundGalleryModal.jsx
// Sound Gallery: browse distinct acoustic profiles across all NASA Earth datasets,
// preview soundscapes, and download high-quality stereo .wav files.
import { useState } from 'react'
import { TRACK_ACOUSTIC_PROFILES } from '../audio/mapping.js'
import { renderSoundscapeWav } from '../audio/engine.js'
import { readColumn } from '../audio/analyse.js'

export default function SoundGalleryModal({
  tracks = [],
  selectedTrack,
  onSelectTrack,
  onClose,
  mediaRef,
  config,
}) {
  const [downloadingId, setDownloadingId] = useState(null)

  const handleDownload = async (track, e) => {
    e.stopPropagation()
    setDownloadingId(track.id)
    try {
      // If active track is the one selected, use its media element
      const mediaEl = mediaRef?.current
      const trackConfig = {
        ...config,
        ...(TRACK_ACOUSTIC_PROFILES[track.id] || {}),
      }
      const metadata = {
        title: track.title || 'Earth Jukebox Sonification',
        credit: track.credit || "NASA's Scientific Visualization Studio",
        comment: 'audio generated by Earth Jukebox code (AI-assisted code, reviewed by the team)',
        date: new Date().toISOString().slice(0, 10),
      }

      if (mediaEl) {
        const wavBlob = await renderSoundscapeWav(readColumn, mediaEl, trackConfig, 14, metadata)
        const url = URL.createObjectURL(wavBlob)
        const a = document.createElement('a')
        a.href = url
        a.download = `${track.id}-soundscape.wav`
        document.body.appendChild(a)
        a.click()
        document.body.removeChild(a)
        URL.revokeObjectURL(url)
      } else {
        alert('Please select this track to load its visual media for download.')
      }
    } catch (err) {
      console.error('Download failed:', err)
      alert('Could not render audio file: ' + err.message)
    } finally {
      setDownloadingId(null)
    }
  }

  return (
    <div className="modal-backdrop" role="dialog" aria-modal="true" aria-labelledby="gallery-heading">
      <div className="gallery-modal">
        <header className="gallery-modal-header">
          <div>
            <span className="gallery-pill">EARTH ACOUSTIC CATALOG</span>
            <h2 id="gallery-heading" className="gallery-title">
              Sound Gallery
            </h2>
          </div>
          <button type="button" className="modal-close-btn" onClick={onClose} aria-label="Close sound gallery">
            ✕
          </button>
        </header>

        <p className="gallery-intro">
          Each Earth visualization generates a unique acoustic signature dictated by its color distribution, optical reflectance, and latitude band dynamics.
        </p>

        <div className="gallery-grid">
          {tracks.map((t) => {
            const profile = TRACK_ACOUSTIC_PROFILES[t.id] || {
              rootNote: 'C3',
              scale: 'pentatonic',
              timbreName: 'Orbital Harmonics',
            }
            const isSelected = t.id === selectedTrack?.id
            const isDownloading = downloadingId === t.id

            return (
              <div
                key={t.id}
                className={`gallery-card ${isSelected ? 'selected' : ''}`}
                onClick={() => onSelectTrack(t)}
              >
                <div className="card-top">
                  <span className="card-key-badge">{profile.rootNote}</span>
                  <span className="card-scale-badge">{profile.scale}</span>
                  {isSelected && <span className="card-active-pill">NOW PLAYING</span>}
                </div>

                <h3 className="card-title">{t.title}</h3>
                <span className="card-timbre">{profile.timbreName}</span>
                <p className="card-desc">{profile.signatureDescription}</p>

                <div className="card-actions">
                  <button
                    type="button"
                    className="gallery-play-btn"
                    onClick={(e) => {
                      e.stopPropagation()
                      onSelectTrack(t)
                    }}
                  >
                    {isSelected ? 'Active View' : 'Load Soundscape'}
                  </button>

                  <button
                    type="button"
                    className="gallery-download-btn"
                    onClick={(e) => handleDownload(t, e)}
                    disabled={isDownloading}
                    title="Export 14-second 16-bit 44.1kHz stereo .wav"
                  >
                    {isDownloading ? 'Rendering...' : 'Download .wav'}
                  </button>
                </div>
              </div>
            )
          })}
        </div>
      </div>
    </div>
  )
}
